"""Requirements traceability: docs/requirements.md -> tests -> latest results.

  python tools/trace.py [--host-results FILE] [--check]

- Parses the requirement table in docs/requirements.md ("| REQ-... | text | host:a, hw:b |").
- Host tests must be registered with RUN(name) in tests/test_core.c.
- Hardware scenarios must exist in tools/bench.py (SCENARIOS / MANUAL dicts).
- Host results: output of the test binary ("ok   name" / "FAIL name"), if given.
- Hardware results: the latest "===== name: PASS|FAIL" line for each scenario across
  logs/*.log (log file names start with a UTC timestamp, so name order = time order).
Writes docs/traceability.md. With --check, exits 1 if a requirement has no verification,
references an unknown test, or its latest known result is a failure.
Standard library only (runs in CI without pyserial).
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def parse_requirements() -> list[tuple[str, str, list[str]]]:
    reqs = []
    for line in (ROOT / "docs" / "requirements.md").read_text(encoding="utf-8").splitlines():
        m = re.match(r"\|\s*(REQ-[A-Z]+-\d+)\s*\|(.*)\|(.*)\|\s*$", line)
        if m:
            refs = [r.strip() for r in m.group(3).split(",") if r.strip()]
            reqs.append((m.group(1), m.group(2).strip(), refs))
    return reqs


def host_tests() -> set[str]:
    src = (ROOT / "tests" / "test_core.c").read_text(encoding="utf-8")
    return set(re.findall(r"^\s*RUN\((\w+)\);", src, flags=re.M))


def hw_scenarios() -> set[str]:
    src = (ROOT / "tools" / "bench.py").read_text(encoding="utf-8")
    names = set()
    for block in re.findall(r"^(?:SCENARIOS|MANUAL|OTA) = \{(.*?)^\}", src, flags=re.M | re.S):
        names |= set(re.findall(r'"(\w+)":', block))
    names |= set(re.findall(r'MANUAL = \{"(\w+)"', src))
    return names


def host_results(path: str | None) -> dict[str, str]:
    if not path:
        return {}
    res = {}
    for line in pathlib.Path(path).read_text(encoding="utf-8", errors="replace").splitlines():
        m = re.match(r"^(ok|FAIL)\s+(\w+)\s*$", line)
        if m:
            res[m.group(2)] = "PASS" if m.group(1) == "ok" else "FAIL"
    return res


def hw_results() -> dict[str, tuple[str, str]]:
    res: dict[str, tuple[str, str]] = {}
    for log in sorted((ROOT / "logs").glob("*.log")):
        for line in log.read_text(encoding="utf-8", errors="replace").splitlines():
            m = re.search(r"===== (\w+): (PASS|FAIL)", line)
            if m:
                res[m.group(1)] = (m.group(2), log.name)
    return res


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--host-results")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    reqs = parse_requirements()
    known_host, known_hw = host_tests(), hw_scenarios()
    hres, wres = host_results(a.host_results), hw_results()
    problems = []
    rows = []
    for rid, text, refs in reqs:
        host_cells, hw_cells, status = [], [], "verified"
        if not refs:
            problems.append(f"{rid}: no verification listed")
            status = "NOT VERIFIED"
        for ref in refs:
            kind, _, name = ref.partition(":")
            if kind == "host":
                if name not in known_host:
                    problems.append(f"{rid}: unknown host test {name}")
                    host_cells.append(f"`{name}` (missing)")
                    status = "BROKEN REF"
                    continue
                r = hres.get(name, "not run")
                if r == "FAIL":
                    problems.append(f"{rid}: host test {name} FAILED")
                    status = "FAILING"
                host_cells.append(f"`{name}`: {r}")
            elif kind == "hw":
                if name not in known_hw:
                    problems.append(f"{rid}: unknown hardware scenario {name}")
                    hw_cells.append(f"`{name}` (missing)")
                    status = "BROKEN REF"
                    continue
                r, log = wres.get(name, ("never run", ""))
                if r == "FAIL":
                    problems.append(f"{rid}: hardware scenario {name} latest result FAIL ({log})")
                    status = "FAILING"
                hw_cells.append(f"`{name}`: {r}" + (f" ({log})" if log else ""))
            else:
                problems.append(f"{rid}: bad reference '{ref}'")
                status = "BROKEN REF"
        if status == "verified" and not any(c.endswith(("PASS",)) or "PASS (" in c
                                            for c in host_cells + hw_cells):
            status = "no result yet"
        rows.append((rid, text, host_cells, hw_cells, status))

    out = ["# Traceability matrix", "",
           "Generated by `tools/trace.py` from [requirements.md](requirements.md), "
           "`tests/test_core.c`, `tools/bench.py` and the hardware logs in `logs/`. "
           "Do not edit by hand.", "",
           f"Host results: {'from ' + pathlib.Path(a.host_results).name if a.host_results else 'not provided'}. "
           "Hardware results: latest run of each scenario found in `logs/`.", "",
           "| ID | Requirement | Host tests | Hardware | Status |", "|---|---|---|---|---|"]
    for rid, text, hc, wc, st in rows:
        out.append(f"| {rid} | {text} | {'<br>'.join(hc) or '-'} | {'<br>'.join(wc) or '-'} | {st} |")
    n_ok = sum(1 for r in rows if r[4] == "verified")
    out += ["", f"{len(rows)} requirements, {n_ok} verified with a passing result."]
    if problems:
        out += ["", "## Problems", ""] + [f"- {p}" for p in problems]
    (ROOT / "docs" / "traceability.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(rows)} requirements, {n_ok} verified, {len(problems)} problem(s)")
    for p in problems:
        print("  PROBLEM:", p)
    return 1 if (a.check and problems) else 0


if __name__ == "__main__":
    sys.exit(main())
